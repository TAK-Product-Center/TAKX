package gov.takx.commons.swing;

import org.junit.jupiter.api.Test;

import javax.swing.tree.DefaultMutableTreeNode;
import javax.swing.tree.DefaultTreeModel;
import javax.swing.tree.TreeModel;

import java.util.ArrayList;
import java.util.List;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * These tests indirectly test {@link TreeModelIterator.NodeChildIterator}, so no distinct tests are included for it.
 *
 * @since 5.3
 */
public class TreeModelIteratorTest
{
    private static final String ROOT = "ROOT";

    @Test
    void defaultIterator_includesRoot()
    {
        final var treeModel = makeTreeModel(1);
        final var root = treeModel.getRoot();
        final var iterator = new TreeModelIterator<>(treeModel, root);

        assertThat(iterator.hasNext()).isTrue();
        assertThat(iterator.next()).isEqualTo(root);
    }

    @Test
    void iterator_producesAllDistinctNodes()
    {
        final var treeModel = makeTreeModel(3);
        final var root = treeModel.getRoot();

        final var allNodes = new ArrayList<>();
        final var iterator = new TreeModelIterator<>(treeModel, root);
        while (iterator.hasNext()) allNodes.add(iterator.next());

        assertThat(allNodes).hasSize(3 * 4 + 1);

        final var distinctNodes = allNodes.stream().distinct().toList();
        assertThat(distinctNodes).isEqualTo(allNodes);
    }

    @Test
    void iterator_whenIncludeStartNodeIsFalse_doesNotIncludeRoot()
    {
        final var treeModel = makeTreeModel(1);
        final var root = treeModel.getRoot();
        final var iterator = new TreeModelIterator<>(treeModel, root, false);

        while (iterator.hasNext()) assertThat(iterator.next()).isNotEqualTo(root);
    }

    @Test
    void iterator_whenIncludeStartNodeIsFalse_onEmptyModel_producesNoNodes()
    {
        final var treeModel = makeTreeModel(0);
        final var root = (DefaultMutableTreeNode) treeModel.getRoot();
        var iterator = new TreeModelIterator<>(treeModel, root, false);

        assertThat(iterator.hasNext()).isFalse();
    }

    @Test
    void iterationOrder_isPreOrderDepthFirst()
    {
        final var treeModel = makeTreeModel(3);
        final var root = (DefaultMutableTreeNode) treeModel.getRoot();
        final var iterator = new TreeModelIterator<>(treeModel, root);

        final var expectedNames = makeNodeNames(3);
        int index = 0;

        while (iterator.hasNext())
        {
            assertThat(iterator.next().getUserObject()).isEqualTo(expectedNames.get(index++));
        }

        assertThat(index).isEqualTo(expectedNames.size());
    }

    @Test
    void streamFromIterator_producesSameNodes()
    {
        final var treeModel = makeTreeModel(3);
        final var root = (DefaultMutableTreeNode) treeModel.getRoot();

        var iterator = new TreeModelIterator<>(treeModel, root);
        final List<DefaultMutableTreeNode> expectedNodes = new ArrayList<>();
        while (iterator.hasNext()) expectedNodes.add(iterator.next());

        iterator = new TreeModelIterator<>(treeModel, root);
        final var actualNodes = iterator.toStream().toList();
        assertThat(actualNodes).containsExactlyElementsOf(expectedNodes);
    }

    @Test
    void streamFromIterator_startsAtCurrentIterationPoint()
    {
        final var treeModel = makeTreeModel(2); // 7 nodes: ROOT, 0, 0_0, 0_1, 1, 1_0, 1_1

        final var root = (DefaultMutableTreeNode) treeModel.getRoot();
        final var iterator = new TreeModelIterator<>(treeModel, root);

        iterator.next();
        iterator.next();
        iterator.next();

        final var expectedNames = makeNodeNames(2);

        assertThat(iterator.toStream().toList())
                .extracting(DefaultMutableTreeNode::getUserObject)
                .containsExactlyElementsOf(expectedNames.subList(3, expectedNames.size()));
    }

    /**
     * @return a tree model with {@code childCount} children under the root node, and each of those nodes having,
     * {@code childCount} children.  Total node count is {@code 1 + nodeCount * (nodeCount + 1)}.
     */
    private TreeModel makeTreeModel(int childCount)
    {
        var root = new DefaultMutableTreeNode(ROOT);
        final var model = new DefaultTreeModel(root);

        for (int i = 0; i < childCount; i++)
        {
            var node = new DefaultMutableTreeNode(String.valueOf(i));
            root.add(node);

            for (int j = 0; j < childCount; j++)
            {
                var child = new DefaultMutableTreeNode(i + "_" + j);
                node.add(child);
            }
        }

        return model;
    }

    /**
     * @return List of node names in the same order as tree nodes generated by {@link #makeTreeModel(int)}
     */
    @SuppressWarnings("SameParameterValue")
    private List<String> makeNodeNames(int childCount)
    {
        final List<String> names = new ArrayList<>();

        names.add(ROOT);

        for (int i = 0; i < childCount; i++)
        {
            names.add(String.valueOf(i));

            for (int j = 0; j < childCount; j++) names.add(i + "_" + j);
        }
        return names;
    }
}
