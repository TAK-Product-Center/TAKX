package gov.takx.api.coordinatesystem;

import jakarta.annotation.Nonnull;

/**
 * Concrete implementation of {@link IExtendedLocation}.
 * @since 3.4
 */
public class ExtendedLocation extends RaptorLocation implements IExtendedLocation
{
    private final boolean userGenerated;
    private final boolean undoOperation;

    /**
     * Construct an extended location object from the given location and set the user generated and undo operation
     * as indicated.
     *
     * @param location      Source location
     * @param userGenerated Pass {@code true} if this is a user generated location
     * @param undoOperation Pass {@code true} if this is a location generated by an undo operation
     */
    public ExtendedLocation(@Nonnull ILocation location, boolean userGenerated, boolean undoOperation)
    {
        super(location);

        this.userGenerated = userGenerated;
        this.undoOperation = undoOperation;
    }

    @Override
    public boolean isUserGenerated()
    {
        return userGenerated;
    }

    @Override
    public boolean isUndoOperation()
    {
        return undoOperation;
    }

    @Override
    public void setLatitude(double lat)
    {
        throwNoSetters();
    }

    @Override
    public void setLongitude(double lon)
    {
        throwNoSetters();
    }

    @Override
    public void setElevation(double elevation)
    {
        throwNoSetters();
    }

    private void throwNoSetters()
    {
        throw new UnsupportedOperationException("Instance does not support setters");
    }
}
