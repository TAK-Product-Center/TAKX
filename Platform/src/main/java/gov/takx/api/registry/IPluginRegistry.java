package gov.takx.api.registry;

import gov.takx.api.annotation.Internal;
import gov.takx.api.annotation.NoPluginImplementations;
import gov.takx.api.plugin.IPluginDefinition;
import gov.takx.api.plugin.IRaptorPlugin;
import gov.takx.api.plugin.PluginCategory;
import jakarta.annotation.Nonnull;
import jakarta.annotation.Nullable;

import java.io.File;
import java.util.Collection;
import java.util.Optional;

/**
 * Base interface for all plugin registries.  Methods common to all plugin registries reside here.
 *
 */
@NoPluginImplementations
public interface IPluginRegistry<T extends IRaptorPlugin, PD extends IPluginDefinition<? extends IRaptorPlugin>>
{
    /**
     * Get the plugin definition for a plugin with the given family and type.
     *
     * @param family Family of desired plugin
     * @param type   Type of desired plugin
     * @return Optional plugin definition
     */
    Optional<PD> getPluginDefinition(@Nonnull String family, @Nonnull String type);

    /**
     * Get the plugin definition for a given plugin instance.
     *
     * @param plugin Plugin instance
     * @return Optional plugin definition
     */
    PD getPluginDefinition(@Nonnull T plugin);

    /**
     * @return The plugin category this registry manages
     * @since 2.0.0
     */
    PluginCategory getPluginCategory();

    /**
     * Get the plugin registered with the given type.
     *
     * @param family The plugin family namespace
     * @param type   Type of plugin to return, may not be {@code null}
     * @return plugin instance, {@code null} if no plugin is registered for that type
     */
    @Nullable
    T getPlugin(@Nonnull String family, @Nonnull String type);

    /**
     * Obtains a collection of all the registered plugin instances.
     *
     * @return non-null Collection of plugin instances
     */
    Collection<T> getPlugins();

    /**
     * Get all the plugin definitions in this registry.
     *
     * @return non-null collection of plugin definitions, may be empty
     */
    Collection<PD> getPluginDefinitions();

    /**
     * Get the plugin source .jar as a File object.
     *
     * @param plugin The plugin of interest
     * @return File (jar) from which the plugin was loaded
     */
    File getPluginSource(@Nonnull T plugin);

    /**
     * Determines if a plugin with the given type and version is registered.
     *
     * @param family  The plugin family namespace
     * @param type    plugin type
     * @param version plugin version
     * @return true, if plugin exists
     */
    boolean exists(@Nonnull String family, @Nonnull String type, @Nonnull String version);

    /**
     * Determines if a plugin with the given type is already registered.
     *
     * @param family The plugin family namespace
     * @param type   plugin type
     * @return true, if plugin exists
     */
    boolean exists(@Nonnull String family, @Nonnull String type);

    /**
     * Add a plugin definition to the registry.  The data needed to register the plugin (family, type and version)
     * will be extracted from the plugin definition.  The definition must be of the expected type ({@code <PD>})
     * or a class cast exception will get thrown.
     *
     * @param pluginDefinition The plugin definition to register
     * @return true if the plugin was actually added, false if it was discarded for any reason
     */
    @Internal
    boolean addPlugin(@Nonnull IPluginDefinition<?> pluginDefinition);

    /**
     * Find plugins based on the jar file that supplied them
     *
     * @param jarFile The file
     * @return The collection of plugins contained in the jar file.
     */
    Collection<T> getPlugins(@Nonnull File jarFile);

    /**
     * Get the ClassLoader responsible for the plugin associated with the given family and type.  This ClassLoader
     * can be used to instantiate classes or load resources from the plugins jar file.  This method will scan
     * all plugins defined via a jar in the {@code plugins} directory as well as all plugin configurations
     * generated by plugin configuration reader (which handles icon-defined MapObject types from the resources).
     * <p>
     * If no plugin or plugin configuration is found, the class loader for the takx client will be returned
     *
     * @param family Plugin family
     * @param type   Plugin type
     * @return ClassLoader for plugin or takx client class loader if not found
     * @since 1.44
     */
    ClassLoader getPluginClassLoader(@Nonnull String family, @Nonnull String type);

    /**
     * Perform validation on each plugin, e.g., ensuring instantiation doesn't throw exceptions.
     * Any that fail validation will be removed from the managed list of plugins in this registry.
     * @since 3.4
     */
    void validatePlugins();
}
