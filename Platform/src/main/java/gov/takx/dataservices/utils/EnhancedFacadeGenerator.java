package gov.takx.dataservices.utils;

import com.google.common.annotations.VisibleForTesting;
import gov.takx.api.annotation.Internal;
import gov.takx.api.messages.IDataField;
import gov.takx.api.messages.IPrePersistRaptorDataMessage;
import gov.takx.api.messages.IStructure;
import gov.takx.platform.utils.ClassLoaderUtil;
import org.apache.commons.text.WordUtils;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import java.lang.invoke.MethodHandles;
import java.lang.reflect.Constructor;
import java.lang.reflect.InvocationTargetException;
import java.util.Map;
import java.util.concurrent.ConcurrentHashMap;
import java.util.function.Function;
import javassist.CannotCompileException;
import javassist.ClassClassPath;
import javassist.ClassPool;
import javassist.CtClass;
import javassist.CtField;
import javassist.CtNewConstructor;
import javassist.CtNewMethod;
import javassist.NotFoundException;

/**
 * Generator to create enhanced RDM facades.  The "basic" RDM facade (as generated by the Build Support plugin)
 * still uses the general field getter/setter methods that take field names as arguments.  That field's name is used
 * in a switch statement to determine the primitive field to operate upon.
 * <p>
 * An <em>Enhanced</em> facade is generated at runtime as a subclass of the basic facade class.  Since it can
 * be generated to make method calls to the actual methods in the dynamically generated extended data structure class
 * (generated by {@code DynamicStructures}), it completely removes the overhead of the switch.
 * <p>
 * Note: the value of this "enhancement" is now likely marginal at best since the dynamic structure code generation
 * moved to using a switch statement vs. a map lookup and reflective method invocation (the reflective invocation being
 * the major component of that operation).  The overhead of the switch is likely immeasurable in the larger scheme of things.
 *
 * @since 2.22
 */
@Internal
public class EnhancedFacadeGenerator
{
    private static final Logger logger = LoggerFactory.getLogger(MethodHandles.lookup().lookupClass());

    // Map of base facade class to generated enhanced facade class
    private static final Map<Class<?>, Class<?>> FACADE_CLASS_MAP = new ConcurrentHashMap<>();

    // Construct our class pool on top of DynamicStructures' class pool so we can find all its generated classes
    private static final ClassPool classPool = new ClassPool(DynamicStructures.getClassPool());

    /**
     * Create the generator function that constructs instances of the enhanced facade class.  The enhanced facade
     * class is generated if it doesn't exist yet.
     * <p>
     * Basic facades generated by the Build Support plugin contain this type of code:
     * <pre>
     * {@code
     * private static Function<IPrePersistRaptorDataMessage, SomeFacade> generator = SomeFacade::new;
     *
     * ...
     *
     * if (!enhancedGeneratorConstructed)
     * {
     *     generator = EnhancedFacadeGenerator.createFacadeGenerator(rdm.getStructure(), SomeFacade.class);
     *     enhancedGeneratorConstructed = true;
     * }}
     * </pre>
     * <p>
     * This method generates the new generator function that can instantiate the enhanced facade class.
     *
     * @param structure       The structure on which the facade is based
     * @param baseFacadeClass The base facade class (from which to generate the enhanced facade class)
     * @param <T>             base facade class type
     * @return generator function, {@code null} on failure
     */
    public static <T> Function<IPrePersistRaptorDataMessage, ? extends T> createFacadeGenerator(IStructure structure, Class<T> baseFacadeClass)
    {
        try
        {
            final Class<?> facadeClass = FACADE_CLASS_MAP.computeIfAbsent(baseFacadeClass, k -> {
                logger.debug("Create enhanced facade for {}", baseFacadeClass);

                return createFacadeClass(structure, baseFacadeClass);
            });

            return (facadeClass != null) ? createConstructorFunction(baseFacadeClass, facadeClass) : null;
        } catch (NoSuchMethodException e)
        {
            logger.error("Unable to generate Enhanced Facade for {}", baseFacadeClass, e);
        }

        return null;
    }

    /**
     * Make the function object that invokes the constructor on the enhanced facade class.
     *
     * @param baseFacadeClass The base facade class (from which to generate the enhanced facade class)
     * @param facadeClass     newly generated enhanced facade class
     * @param <T>             base facade class type
     * @return function, {@code null} on failure
     * @throws NoSuchMethodException If the needed constructor can't be found
     */
    private static <T> Function<IPrePersistRaptorDataMessage, ? extends T> createConstructorFunction(Class<T> baseFacadeClass, Class<?> facadeClass) throws NoSuchMethodException
    {
        final Constructor<?> constructor = facadeClass.getConstructor(IPrePersistRaptorDataMessage.class);

        return rdm -> {
            try
            {
                //noinspection unchecked
                return (T) constructor.newInstance(rdm);
            } catch (InstantiationException | IllegalAccessException | InvocationTargetException e)
            {
                logger.error("Failed to instantiate Enhanced Facade for {} from {}", baseFacadeClass, rdm, e);
            }
            return null;
        };
    }

    /**
     * Create the enhanced facade class from the given structure and base facade class.
     *
     * @param structure       The structure on which the facade is based
     * @param baseFacadeClass The base facade class (from which to generate the enhanced facade class)
     * @return dynamically created class, {@code null} on failure
     */
    private static Class<?> createFacadeClass(IStructure structure, Class<?> baseFacadeClass)
    {
        structure.createExtendedDataClass(); // Force the generation of the extended data class

        // Make a name that is unique since multiple base facades could, in theory, be based on the same
        // underlying RDM structure.

        final String structureClassName = structure.getExtendedDataClassName();
        final String facadeClassName = "enhanced$" + structureClassName + "$" + baseFacadeClass.getSimpleName();

        try
        {
            classPool.insertClassPath(new ClassClassPath(baseFacadeClass));

            final CtClass ctClass = classPool.makeClass(facadeClassName);
            final CtClass structureCtClass = classPool.get(structureClassName);
            ctClass.setSuperclass(classPool.get(baseFacadeClass.getName()));

            // Construct the data object field
            ctClass.addField(new CtField(structureCtClass, "dataObject", ctClass));

            // Give it a constructor
            final String ctorBody = String.format("public %s(gov.takx.api.messages.IPrePersistRaptorDataMessage rdm) { super(rdm); dataObject = (%s) rdm.getDataObject(); }", ctClass.getName(), structureClassName);
            logger.trace("CTOR: {}", ctorBody);
            ctClass.addConstructor(CtNewConstructor.make(ctorBody, ctClass));

            // Process every field in the structure and generate the accessor methods for them

            for (IDataField dataField : structure.getFields())
            {
                createFieldAccessors(ctClass, baseFacadeClass, dataField);
            }

            // Since these classes come from plugins, push the ClassLoader for the base facade class

            ClassLoaderUtil.pushContextClassLoader(baseFacadeClass.getClassLoader());

            try
            {
                return ctClass.toClass();
            } finally
            {
                ClassLoaderUtil.popContextClassLoader();
            }
        } catch (NotFoundException | CannotCompileException e)
        {
            logger.error("Failed to generate Enhanced Facade for {}", baseFacadeClass, e);
        }

        return null;
    }

    /**
     * Create the field accessor methods for the given data field.
     *
     * @param ctClass   Class being created
     * @param dataField data field to process
     * @throws CannotCompileException If generated code can't be compiled
     */
    @SuppressWarnings("ReturnValueIgnored") // suppress errorprone check on the call to getDeclaredMethod below
    private static void createFieldAccessors(CtClass ctClass, Class<?> baseFacadeClass, IDataField dataField) throws CannotCompileException
    {
        final String camelCaseName = makeCamelCaseName(dataField);
        final Class<?> fieldType = dataField.getJavaType();
        final String typeName = fieldType.getSimpleName();

        // Getter and isNull methods
        final String getterMethodName = DynamicStructures.getGetterMethodName(dataField);
        final String facadeMethodName = "get" + camelCaseName;
        final String getterBody = String.format("public %s %s() { return dataObject.%s(); }", typeName, facadeMethodName, getterMethodName);
        logger.trace("   getter {}: {}", facadeMethodName, getterBody);
        ctClass.addMethod(CtNewMethod.make(getterBody, ctClass));

        // Detect problems where the basic facade generation and this enhanced facade generation don't come up with
        // the same method names and report it.
        try
        {
            baseFacadeClass.getDeclaredMethod(facadeMethodName);
        } catch (NoSuchMethodException e)
        {
            logger.warn("""
                    The facade method '{}' does not match a method from the base facade class '{}'
                    This is probably a failure to properly match the method name to the structure field name '{}'
                    Performance will not be optimal for this method.""",
                    facadeMethodName, baseFacadeClass.getName(), dataField.getFieldName());
        }

        final String isNullMethodName = DynamicStructures.getIsNullMethodName(dataField);
        final String isNullBody = String.format("public boolean is%sNull() { return dataObject.%s(); }", camelCaseName, isNullMethodName);
        logger.trace("   isNull {}: {}", camelCaseName, isNullBody);
        ctClass.addMethod(CtNewMethod.make(isNullBody, ctClass));

        // Setter and setNull methods
        final String setterMethodName = DynamicStructures.getSetterMethodName(dataField);

        // We want to intern all strings to minimize our memory footprint
        final String valueToSet = fieldType == String.class ? "_$_val.intern()" : "_$_val";
        final String setterBody = String.format("public void set%s(%s _$_val) { dataObject.%s(%s); }", camelCaseName, typeName, setterMethodName, valueToSet);
        logger.trace("   setter {}: {}", camelCaseName, setterBody);
        ctClass.addMethod(CtNewMethod.make(setterBody, ctClass));

        final String setNullMethodName = DynamicStructures.getSetNullMethodName(dataField);
        final String setNullBody = String.format("public void set%sNull() { dataObject.%s(); }", camelCaseName, setNullMethodName);
        logger.trace("   setNull {}: {}", camelCaseName, setNullBody);
        ctClass.addMethod(CtNewMethod.make(setNullBody, ctClass));
    }

    /**
     * Make the camel case name for the given data field.  The field name is broken apart on "non-word" characters
     * (using the regex pattern {@code "\\W"}), and then those words are capitalized.
     * <p>
     * For example, a field named {@code "foo bar-baz"} would result in a camel case name of {@code "FooBarBaz"}.
     *
     * @param dataField data field to process
     * @return camel cased name
     */
    @VisibleForTesting
    static String makeCamelCaseName(IDataField dataField)
    {
        final String fieldName = dataField.getFieldName();
        String cleanName = fieldName.replaceAll("\\W", "_");

        // Force to lower case only if there are delimiters present
        // This handles cases where the field name is a simple acronym, like MCC, and we want to generate method
        // names like setMCC and not setMcc.

        if (cleanName.indexOf('_') >= 0) cleanName = cleanName.toLowerCase();

        return WordUtils.capitalize(cleanName, '_').replaceAll("_", "");
    }
}
