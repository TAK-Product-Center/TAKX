package gov.takx.core.routes;

import de.micromata.opengis.kml.v_2_2_0.AltitudeMode;
import de.micromata.opengis.kml.v_2_2_0.Container;
import de.micromata.opengis.kml.v_2_2_0.Data;
import de.micromata.opengis.kml.v_2_2_0.ExtendedData;
import de.micromata.opengis.kml.v_2_2_0.Folder;
import de.micromata.opengis.kml.v_2_2_0.Kml;
import de.micromata.opengis.kml.v_2_2_0.KmlFactory;
import de.micromata.opengis.kml.v_2_2_0.LineString;
import de.micromata.opengis.kml.v_2_2_0.Placemark;
import de.micromata.opengis.kml.v_2_2_0.Point;
import de.micromata.opengis.kml.v_2_2_0.Style;
import gov.tak.api.engine.map.coords.IGeoPoint;
import gov.tak.api.maps.coords.GeoPointMetaData;
import gov.tak.api.util.AttributeSet;
import gov.takx.api.shapes.IRoute;
import gov.takx.commons.utils.PlatformVersion;
import gov.takx.commons.xml.gpx.GPX;
import gov.takx.commons.xml.kml.DefaultNamespaceKml;
import jakarta.annotation.Nonnull;
import org.apache.commons.text.WordUtils;

import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.util.Locale;

import static gov.tak.api.util.StandardAttributeNames.UID;
import static gov.takx.api.shapes.IRoute.IS_A_WAYPOINT;

/**
 * A utility class to export a {@link IRoute} to a file-writable data model.
 * @since 5.8
 */
public class RouteExportService
{
    private static final String DESCRIPTION = "Generated by TAKX " + PlatformVersion.CURRENT_VERSION_STRING + " on: %s UTC";
    public static final DateTimeFormatter TIME_FORMAT = DateTimeFormatter.ofPattern("HHmmss");
    public static final DateTimeFormatter DATE_FORMAT = DateTimeFormatter.ofPattern("yyyy-MM-dd-HH-mm-ss");

    /**
     * Route export file type options
     */
    public enum FileType
    {
        GPX, KML, KMZ
    }

    /**
     * @param route The route to export
     * @param fileName the name of the file to use for the KML "name" element
     * @param utcDatetime the time the route was exported for use in the "description" element
     * @return KML model of the route
     */
    @Nonnull
    public static Kml buildRouteKml(@Nonnull IRoute route, @Nonnull String fileName, @Nonnull LocalDateTime utcDatetime)
    {
        var kml = new DefaultNamespaceKml();
        var document = kml.createAndSetDocument().withName(fileName + ".kml").withDescription(DESCRIPTION.formatted(utcDatetime.format(DATE_FORMAT)));

        // create + add styles to document
        Style routeStyle = addStyle(document, route, false);
        Style waypointStyle = addStyle(document, route, true);
        String waypointStyleId = "#" + waypointStyle.getId();
        Folder navigationFolder = document.createAndAddFolder().withName("Navigation").withOpen(true);
        boolean routeVisibility = route.isVisible();
        Placemark routePlacemark = navigationFolder.createAndAddPlacemark().withName(route.getName())
                .withVisibility(routeVisibility).withStyleUrl("#" + routeStyle.getId())
                .withExtendedData(new ExtendedData().addToData(new Data(route.getDirection().getDisplayText()).withName("PlanningMethod"))
                        .addToData(new Data(route.getDirection().getDisplayText()).withName("RouteDirection"))
                        .addToData(new Data(route.getMethod().getDisplayText()).withName("RouteMethod"))
                        .addToData(new Data(WordUtils.capitalize(route.getRouteOrder().name())).withName("RouteOrder"))
                        .addToData(new Data(route.getRouteType().getDisplayText()).withName("RouteType")));
        LineString routeGeometry = new LineString().withAltitudeMode(AltitudeMode.ABSOLUTE);
        for (GeoPointMetaData gpmd : route.getControlPoints())
        {
            IGeoPoint geoPoint = gpmd.get();
            AttributeSet gpmdMetaData = gpmd.getMetaData();
            double lon = geoPoint.getLongitude();
            double lat = geoPoint.getLatitude();
            double alt = geoPoint.getAltitude();
            routeGeometry.addToCoordinates(lon, lat, alt);
            if (gpmdMetaData.getBooleanAttribute(IS_A_WAYPOINT, false))
            {
                Point pointGeometry = new Point().withExtrude(true).withAltitudeMode(AltitudeMode.ABSOLUTE).addToCoordinates(lon, lat, alt);
                navigationFolder.addToFeature(new Placemark().withName(gpmdMetaData.getStringAttribute(IRoute.DISPLAY_NAME))
                        .withVisibility(routeVisibility).withGeometry(pointGeometry).withStyleUrl(waypointStyleId));
            }
        }
        routePlacemark.withGeometry(routeGeometry);
        return kml;
    }

    /**
     * @param container The document or folder to which the style should be added
     * @param route The route
     * @param isCheckpointStyle Include an icon HREF in the icon style
     * @return A style that was added to the container
     */
    @Nonnull
    private static Style addStyle(@Nonnull Container container, @Nonnull IRoute route, boolean isCheckpointStyle)
    {
        Style containerStyle = container.createAndAddStyle();
        final var colorHexString = Integer.toHexString(route.getLineColor().getRGB()).toLowerCase(Locale.ROOT);

        if (isCheckpointStyle)
        {
            final var iconStyle = KmlFactory.createIconStyle().withColor(colorHexString);
            iconStyle.createAndSetIcon().withHref("http://maps.google.com/mapfiles/kml/paddle/wht-circle.png"); // Matches WinTAK's default icon
            containerStyle.withIconStyle(iconStyle).withId(String.valueOf(1 + iconStyle.hashCode()));
        } else
        {
            final var polyStyle = KmlFactory.createPolyStyle().withFill(false).withOutline(true);
            final var lineStyle = KmlFactory.createLineStyle().withColor(colorHexString).withWidth(4);
            containerStyle.withPolyStyle(polyStyle).withLineStyle(lineStyle)
                    .withId(String.valueOf(1 + lineStyle.getColor().hashCode() + Double.hashCode(lineStyle.getWidth())));
        }

        return containerStyle;
    }

    /**
     * @param route The route to export
     * @param utcDatetime the time the route was exported for use in the "description" element
     * @return {@link GPX} model of the route
     */
    @Nonnull
    public static GPX buildRouteGpx(@Nonnull IRoute route, @Nonnull LocalDateTime utcDatetime)
    {
        GPX gpx = new GPX().withCreator(DESCRIPTION.formatted(utcDatetime.format(DATE_FORMAT)));
        GPX.GpxRoute.Builder rte = new GPX.GpxRoute.Builder().withName(route.getName());
        for (GeoPointMetaData gpmd : route.getControlPoints())
        {
            IGeoPoint geoPoint = gpmd.get();
            GPX.GpxPoint gpxPoint = new GPX.GpxPoint(geoPoint.getLatitude(), geoPoint.getLongitude(), geoPoint.getAltitude());
            rte.withPoint(gpxPoint);
            AttributeSet gpmdMetaData = gpmd.getMetaData();
            if (gpmdMetaData.getBooleanAttribute(IS_A_WAYPOINT, false))
            {
                // is a promoted gpxPoint, so add as a waypoint too
                String displayName = gpmdMetaData.getStringAttribute(IRoute.DISPLAY_NAME, null);
                String uid = gpmdMetaData.getStringAttribute(UID, null);
                if (displayName == null || uid == null) continue; // skip malformed (no name, uid) waypoints. They are still added as route points.
                gpxPoint.withName(displayName).withDescription(uid);
                gpx.addWaypoint(gpxPoint);
            }
        }
        return gpx.addRoute(rte.build());
    }
}
