package gov.takx.core.globe.tak.elevation;

import com.atakmap.map.elevation.ElevationSource;
import com.atakmap.spi.InteractivePriorityServiceProviderRegistry2;
import com.atakmap.spi.InteractiveServiceProvider;
import gov.takx.api.layer.IRaptorLayer;
import gov.takx.api.terrain.experimental.ITakElevationModel;
import jakarta.annotation.Nonnull;
import jakarta.annotation.Nullable;
import jakarta.enterprise.context.ApplicationScoped;

/**
 * A factory for creating a {@link ElevationSource} and {@link ITakElevationModel} pair from an {@link IRaptorLayer}.
 *
 * @since 5.3
 */
@ApplicationScoped
public class ElevationLayerFactory
{
    private static final InteractivePriorityServiceProviderRegistry2<ElevationLayerPair, IRaptorLayer, ElevationLayerFactorySpi> registry =
            new InteractivePriorityServiceProviderRegistry2<>();

    static
    {
        registerSpi(DtedElevationLayerSpi.SPI);
        registerSpi(StreamingTilesElevationLayerSpi.SPI);
        registerSpi(WcsElevationLayerSpi.SPI);
        registerSpi(GdalElevationLayerSpi.SPI);
        registerSpi(TileContainerElevationLayerSpi.SPI);
    }

    public static void registerSpi(ElevationLayerFactorySpi spi)
    {
        synchronized (registry)
        {
            registry.register(spi, spi.getPriority());
        }
    }

    public static void unregisterSpi(ElevationLayerFactorySpi spi)
    {
        synchronized (registry)
        {
            registry.unregister(spi);
        }
    }

    /**
     * Determines if the factory can create a {@link ElevationSource} and {@link ITakElevationModel} pair for the provided {@link IRaptorLayer}.
     *
     * @param raptorLayer the raptor layer
     * @return {@code true} if the factory can create elevation classes for the raptor layer, or {@code false} if it can not
     */
    public boolean isSupported(IRaptorLayer raptorLayer)
    {
        synchronized (registry)
        {
            return registry.isSupported(raptorLayer, 10);
        }
    }

    /**
     * Create a {@link ElevationSource} and {@link ITakElevationModel} pair for the provided {@link IRaptorLayer} or {@code null} if none can be provided.
     * @param raptorLayer the raptor layer
     * @return a pair of elevation class instances for the raptor layer or {@code null}
     */
    @Nullable
    public ElevationLayerPair create(IRaptorLayer raptorLayer)
    {
        synchronized (registry)
        {
            return registry.create(raptorLayer);
        }
    }

    /**
     * Create a {@link ElevationSource} and {@link ITakElevationModel} pair for the provided {@link IRaptorLayer} and {@link InteractiveServiceProvider.Callback}
     * or {@code null} if none can be provided.
     *
     * @param raptorLayer the raptor layer
     * @param callback an interactive callback, or {@code null}
     * @return a pair of elevation class instances for the raptor layer or {@code null}
     */
    @Nullable
    public ElevationLayerPair create(@Nonnull IRaptorLayer raptorLayer, @Nullable InteractiveServiceProvider.Callback callback)
    {
        synchronized (registry)
        {
            return registry.create(raptorLayer, callback);
        }
    }

    /**
     * A record to store a paired {@link ElevationSource} and {@link ITakElevationModel} generated by {@link ElevationLayerFactory}.
     */
    public record ElevationLayerPair(ElevationSource elevationSource, ITakElevationModel elevationModel)
    {
    }
}
