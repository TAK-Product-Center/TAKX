package gov.takx.core.messagequery;

import gov.takx.api.annotation.PseudoBean;
import gov.takx.api.event.mapobject.MapEntityStructuresUpdated;
import gov.takx.api.mapobject.IMapObject;
import gov.takx.api.messages.IRaptorDataMessage;
import gov.takx.api.messages.IRaptorDataStructure;
import gov.takx.api.query.IDeviceQueryService;
import gov.takx.api.query.IQueryConstraints;
import gov.takx.api.query.IQueryService;
import gov.takx.platform.query.QueryConstraints;
import jakarta.enterprise.event.Observes;

import java.util.HashSet;
import java.util.Set;

/**
 * An {@link IQueryService} implementation specific to plugin instances.  The query domain for this
 * service is the subset of {@link IRaptorDataMessage}s that were generated by the specific plugin instance
 * that instantiated this service.
 */
@SuppressWarnings("CdiManagedBeanInconsistencyInspection")
@PseudoBean
public class PluginQueryService extends AQueryService implements IDeviceQueryService
{
    private Set<IRaptorDataStructure> messageStructures;
    private final IMapObject mapObject;

    private final Object messageStructuresLock = new Object();

    /**
     * Constructor for the specified device/plugin instance.  The device type and unit ID constrain
     * the query domain to messages generated by this plugin only.
     *
     * @param mapObject         Map object defining the query domain
     * @param messageStructures The message structures defined for this device
     */
    public PluginQueryService(IMapObject mapObject, Set<IRaptorDataStructure> messageStructures)
    {
        this.mapObject = mapObject;
        this.messageStructures = new HashSet<>(messageStructures); // Get our own list
    }

    @Override
    public IQueryConstraints createEmptyConstraints()
    {
        QueryConstraints qc = new QueryConstraints();

        // Restrict the domain to just this plugin instance and tell it about our structures
        qc.setMapObject(mapObject);
        synchronized (messageStructuresLock)
        {
            qc.addKnownMessageStructures(messageStructures);
        }

        return qc;
    }

    /**
     * Structures have been re-defined for a Map Entity.  Check to see if the MO is related to the ME, and if so we
     * will need to use the new structures.
     *
     * @param event the structure re-defined event
     * @since 5.5.1
     */
    private void onStructuresRedefined(@Observes MapEntityStructuresUpdated event)
    {
        if (mapObject.getMapEntity() == event.mapEntity())
        {
            synchronized (messageStructuresLock)
            {
                messageStructures = new HashSet<>(mapObject.getMapEntity().getRaptorDataStructures());
            }
        }
    }
}
