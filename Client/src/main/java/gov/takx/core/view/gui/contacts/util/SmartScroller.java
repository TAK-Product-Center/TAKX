package gov.takx.core.view.gui.contacts.util;

import gov.takx.api.annotation.InvokeOnEDT;
import jakarta.annotation.Nonnull;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import javax.swing.JScrollBar;
import javax.swing.JScrollPane;

import java.awt.event.AdjustmentEvent;
import java.awt.event.AdjustmentListener;
import java.awt.event.MouseWheelEvent;
import java.awt.event.MouseWheelListener;
import java.lang.invoke.MethodHandles;

/**
 * The class will keep the viewport positioned according to the user's last interaction with the scrollbar. The normal 
 * JScrollPane behaviour is to automatically scroll to display new data.
 * <p/>
 * This class will take the following actions:
 *     <ul>
 *         <li>if the viewport is at the bottom and new data is added, adjust the view to show the new data</li>
 *         <li>if the viewport is not at the bottom and new data is added, maintain the current view</li>
 *     </ul>
 * When the user drags the scrollbar, multiple events are fired. {@link AdjustmentEvent#getValueIsAdjusting()} will 
 * return {@code true} until the user completes the drag. We can use this to determine that the adjustment was made by 
 * the user.
 * <p/>
 * In contrast, when the user scrolls with the mouse wheel, there is no direct way to determine that the resulting 
 * {@link AdjustmentEvent AdjustmentEvents} were generated by a user action. Additionally, if the scroll bar's 
 * {@code unitIncrement} is greater than 1, each {@link MouseWheelEvent} will generate multiple 
 * {@link AdjustmentEvent AdjustmentEvents}. We handle this by tracking the unit increments in {@link #userScrollCount}
 * (obtained via {@link MouseWheelEvent#getScrollAmount()}) and assuming the corresponding number of 
 * {@link AdjustmentEvent AdjustmentEvents} will be fired and are therefore user-generated, with some edge cases 
 * described inline below.
 * <p/>
 * Note that this class expects the {@link JScrollPane} passed to the constructor to only have the default
 * {@code MouseWheelListener} and will throw an {@link  IllegalArgumentException} if there are additional listeners. If 
 * the the {@link JScrollPane} needs additional listeners, they must be added after it is passed to this class.
 * 
 * @since 3.0 (rewritten in 5.2 to handle JScrollPanes with non-JTextComponent contents) 
 */
public class SmartScroller implements AdjustmentListener
{
    private static final Logger logger = LoggerFactory.getLogger(MethodHandles.lookup().lookupClass());

    private final JScrollBar scrollBar;
    private int previousValue = -1; // last scrollbar position set by the user
    private int userScrollCount; // the scroll count, which translates to the expected AdjustmentEvent count
    private boolean atBottom = true; // flag that indicates the scroll bar should keep the bottom in view

    /**
     * Specify how the SmartScroller will function.
     *
     * @param scrollPane the scroll pane to monitor
     * @throws IllegalArgumentException if the scroll pane has more than one listener
     */
    public SmartScroller(JScrollPane scrollPane)
    {
        scrollBar = scrollPane.getVerticalScrollBar();
        scrollBar.addAdjustmentListener(this);

        // Wrap and re-add the default mouse wheel listener
        final MouseWheelListener[] listeners = scrollPane.getMouseWheelListeners();

        if (listeners.length != 1)
        {
            throw new IllegalArgumentException("Expected 1 (default) MouseWheelListener, but found " + listeners.length
                    + " listeners.");
        }

        final MouseWheelListener mouseWheelListener = listeners[0];
        scrollPane.removeMouseWheelListener(mouseWheelListener);
        scrollPane.addMouseWheelListener(new MouseWheelListenerWrapper(mouseWheelListener));
    }

    @InvokeOnEDT
    @Override
    public void adjustmentValueChanged(final AdjustmentEvent e)
    {
        // This will return true when the user is in the process of dragging the scroll bar. When dragging ends, a
        // final event will be fired that will return false and allow us to update state
        if (e.getValueIsAdjusting())
        {
            if (userScrollCount == 0) logger.debug("Ignoring AdjustmentEvents while adjusting");

            userScrollCount = 1;
            return;
        }

        checkScrollBar();
    }

    /**
     * @return boolean indicating if the scrollbar is currently at the bottom of the view
     * @since 5.2
     */
    public boolean isAtBottom()
    {
        return atBottom;
    }

    /**
     * Forces the scrollbar to scroll to the bottom of the view.
     * 
     * @since 5.2
     */
    public void scrollToBottom()
    {
        userScrollCount = 0;
        atBottom = true;
        checkScrollBar();
    }

    /**
     * Analyze adjustment events to determine when the viewport needs to be repositioned.
     */
    private void checkScrollBar()
    {
        final var boundedRangeModel = scrollBar.getModel();
        final int maximum = boundedRangeModel.getMaximum();
        final int extent = boundedRangeModel.getExtent();

        // If the scroll count is > 0, the user is currently scrolling
        if (userScrollCount-- > 0)
        {
            final int value = boundedRangeModel.getValue();
            final boolean scrollingUp = value < previousValue;

            // Update state
            previousValue = value;
            atBottom = value + extent == maximum;

            // Clear scroll count if the user is scrolling past the top or bottom
            if (value == 0 && scrollingUp || atBottom && !scrollingUp) userScrollCount = 0;

            logger.debug("User scroll detected. Updated state. value: {} bottom: {}, remaining scroll count: {}",
                    previousValue, atBottom, userScrollCount);

            return; // Don't override user scrolling
        }

        // Set the scroll bar to the previous value to undo scrolling caused by new data
        setScrollBarValueQuietly(scrollBar, atBottom ? maximum - extent : previousValue);
    }

    /**
     * Removes adjustment listener while setting new scrollbar value to prevent event loop.
     * 
     * @param scrollBar The scrollbar to update
     * @param value The new scrollbar value
     * @since 5.2
     */
    private void setScrollBarValueQuietly(@Nonnull JScrollBar scrollBar, int value)
    {
        final int currentValue = scrollBar.getValue();

        if (currentValue == value) return;

        logger.debug("Overriding scrollbar value, from {} to {}", currentValue, value);

        scrollBar.removeAdjustmentListener(this);
        scrollBar.setValue(value);
        scrollBar.addAdjustmentListener(this);
    }

    /**
     * Wraps a MouseWheelListener. Updates the {@link #userScrollCount} with the scroll amount before passing the event
     * to the original listener. This is required to detect and handle mouse wheel scrolls and differentiate the
     * resulting events from programmatic scrollbar adjustments.
     * <p/>
     * The scroll count will result in the same number of AdjustmentEvents, unless the top or bottom boundary is reached.
     *
     * @since 5.2
     */
    private class MouseWheelListenerWrapper implements MouseWheelListener
    {
        private final MouseWheelListener mouseWheelListener;

        public MouseWheelListenerWrapper(@Nonnull MouseWheelListener mouseWheelListener)
        {
            this.mouseWheelListener = mouseWheelListener;
        }

        @Override
        public void mouseWheelMoved(MouseWheelEvent e)
        {
            userScrollCount = scrollingPastEdge(e)
                    ? 0 // No AdjustmentEvents will be fired if the user is at the end of the view
                    : e.getScrollAmount(); // Each scroll increment will result in a separate AdjustmentEvent

            logger.debug("Detected scroll wheel moved with scroll amount = {}", userScrollCount);

            // Forward the call to the wrapped listener. This will fire the calls to the AdjustmentListeners
            mouseWheelListener.mouseWheelMoved(e);
        }

        /**
         * @param e the wheel event
         * @return {@code true} if the user is scrolling but has reached the end of the view
         */
        private boolean scrollingPastEdge(MouseWheelEvent e)
        {
            final int wheelRotation = e.getWheelRotation();

            return atBottom && wheelRotation > 0 // at bottom and scrolling down
                    || scrollBar.getValue() == 0 && wheelRotation < 0; // at top and scrolling up
        }
    }
}
