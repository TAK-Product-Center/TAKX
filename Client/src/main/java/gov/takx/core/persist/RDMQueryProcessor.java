package gov.takx.core.persist;

import gov.takx.api.annotation.ProgramPreference;
import gov.takx.api.messages.IRaptorDataMessage;
import gov.takx.api.query.param.HQLParameter;
import gov.takx.api.query.param.SQLTransformer;
import gov.takx.platform.preferences.PreferenceEntry;
import gov.takx.platform.utils.DatabaseUtils;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.inject.Inject;
import org.hibernate.HibernateException;
import org.hibernate.NonUniqueResultException;
import org.hibernate.Session;
import org.hibernate.query.TupleTransformer;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import java.lang.invoke.MethodHandles;
import java.lang.reflect.Constructor;
import java.lang.reflect.InvocationTargetException;
import java.math.BigInteger;
import java.sql.Connection;
import java.sql.Date;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.ResultSetMetaData;
import java.sql.SQLException;
import java.sql.Timestamp;
import java.util.ArrayList;
import java.util.Iterator;
import java.util.List;
import java.util.NoSuchElementException;
import java.util.stream.Collectors;
import java.util.stream.Stream;

/**
 * This class handles processing (parsing and executing) RDM query strings and parameter bindings.
 * It supports a subset of the full syntax allowed by hibernate and was primarily implemented to avoid having to
 * hunt down and convert all the existing HQL queries into native SQL.
 *
 * @since 2.14
 */
@ApplicationScoped
public class RDMQueryProcessor
{
    private static final Logger logger = LoggerFactory.getLogger(MethodHandles.lookup().lookupClass());

    private final RDMQueryParser queryParser;
    private final MessagePersistHelper persistHelper;
    private final boolean setFetchSizeEnabled;

    /**
     * CDI constructor.
     *
     * @since 2.37
     */
    @Inject
    RDMQueryProcessor(RDMQueryParser queryParser, MessagePersistHelper persistHelper,
                      @ProgramPreference(PreferenceEntry.ENABLE_SET_FETCH_SIZE) boolean setFetchSizeEnabled)
    {
        this.queryParser = queryParser;
        this.persistHelper = persistHelper;
        this.setFetchSizeEnabled = setFetchSizeEnabled;
    }

    /**
     * Perform a query.
     *
     * @param session    DB session to use
     * @param hql        The HQL query to parse and execute
     * @param parameters The parameters to bind
     * @return List of results (content depends on the query)
     */
    public List<?> query(Session session, String hql, HQLParameter... parameters) throws HibernateException
    {
        return query(session, hql, null, parameters);
    }

    /**
     * Perform a query with an optional limit on the number of results returned.
     *
     * @param session    DB session to use
     * @param hql        The HQL query to parse and execute
     * @param maxRows    The maximum number of results to return (<= 0 or {@code null} means no limit)
     * @param parameters The parameters to bind
     * @return List of results (content depends on the query)
     */
    public <T> List<T> query(Session session, String hql, Integer maxRows, HQLParameter... parameters) throws HibernateException
    {
        return queryInternal(session, parseQuery(hql), maxRows, parameters);
    }

    /**
     * Perform a query for a unique result.
     *
     * @param session    DB session to use
     * @param hql        The HQL query to parse and execute
     * @param parameters The parameters to bind
     * @return Single result (content depends on the query)
     * @throws NonUniqueResultException If more than a single result row was returned from the query
     */
    public <T> T queryUnique(Session session, String hql, HQLParameter... parameters) throws HibernateException
    {
        final List<?> results = query(session, hql, null, parameters);
        final int size = results.size();

        if (size > 1) throw new NonUniqueResultException(size);

        //noinspection unchecked
        return size == 0 ? null : (T) results.get(0);
    }

    /**
     * Perform a query on the given SQL (not HQL, SQL).  The SQL is not parsed except to locate parameter binding
     * locations.  Name-based parameter bindings are supported (like ':someValue') within the SQL.
     * <p>
     * This method is primarily used to handle the SQL generated by the query service.
     *
     * @param session    DB session to use
     * @param sql        SQL to process
     * @param maxRows    The maximum number of results to return (<= 0 or {@code null} means no limit)
     * @param asMessages Pass {@code true} to reify the results as RDMs, or {@code false} for "custom" selects
     * @param parameters The parameters to bind
     * @return List of results
     */
    public <T> List<T> querySQL(Session session, String sql, Integer maxRows, boolean asMessages, HQLParameter... parameters) throws HibernateException
    {
        return queryInternal(session, queryParser.fromSql(sql, asMessages), maxRows, parameters);
    }

    /**
     * Perform a query on the given SQL (not HQL, SQL) and return an iterator on the results.
     * The SQL is not parsed except to locate parameter binding locations.
     * Name-based parameter bindings are supported (like ':someValue') within the SQL.
     * <p>
     * This method is primarily used to handle the SQL generated by the query service.
     * <p>
     * Note that the returned iterator implements {@link AutoCloseable}, supporting use in a try-with-resources block,
     * releasing the underlying database resources.
     *
     * @param connection DB connection to use
     * @param sql        SQL to process
     * @param maxRows    The maximum number of results to return (<= 0 or {@code null} means no limit)
     * @param parameters The parameters to bind
     * @return Iterator of RDMs
     */
    public Iterator<IRaptorDataMessage> iteratorSQL(Connection connection, String sql, Integer maxRows, HQLParameter... parameters) throws HibernateException
    {
        final var managedQuery = performQuery(connection, queryParser.fromSql(sql, true), maxRows, parameters);
        return new ResultSetIterator(connection, managedQuery, persistHelper);
    }

    /**
     * Create an RDMQuery from the given HQL.
     *
     * @param hql HQL to parse
     * @return RDMQuery
     * @throws HibernateException If parsing fails
     */
    private RDMQuery parseQuery(String hql) throws HibernateException
    {
        try
        {
            return queryParser.parse(hql);
        } catch (SQLException e)
        {
            logger.error("Failed to parse RDM query: {}", hql, e);
            throw new HibernateException("Failed to parse RDM query", e);
        }
    }

    /**
     * Internal query processing.  Execute the given query and return the result list.
     *
     * @param session    DB session to use
     * @param query      Query to process
     * @param maxRows    The maximum number of results to return (<= 0 or {@code null} means no limit)
     * @param parameters The parameters to bind
     * @return List of RDMs
     */
    private <T> List<T> queryInternal(Session session, RDMQuery query, Integer maxRows, HQLParameter... parameters) throws HibernateException
    {
        try
        {
            //noinspection unchecked
            return (List<T>) session.doReturningWork(connection -> {
                final List<?> result;

                try (final ManagedQuery managedQuery = performQuery(connection, query, maxRows, parameters))
                {
                    final ResultSet resultSet = managedQuery.resultSet;

                    if (query.isCustomSelect())
                    {
                        final List<?> values = reifyValues(resultSet, getResultTransformer(parameters));

                        // If we are constructing custom objects, then create them.  Otherwise, return the values.

                        result = query.isConstructNewClass()
                                ? constructInstances(query.getNewClassName(), values, resultSet.getMetaData())
                                : values;
                    } else
                    {
                        result = persistHelper.reifyRDMs(resultSet);
                    }
                }

                connection.commit();

                return result;
            });
        } catch (HibernateException e)
        {
            logger.error("queryInternal failed", e);
            throw e;
        }
    }

    /**
     * Execute the given query and obtain a ManagedQuery holding the ResultSet.
     *
     * @param connection DB connection to use
     * @param query      Query to process
     * @param maxRows    The maximum number of results to return (<= 0 or {@code null} means no limit)
     * @param parameters The parameters to bind
     * @return ManagedQuery
     * @since 2.37
     */
    private ManagedQuery performQuery(Connection connection, RDMQuery query, Integer maxRows, HQLParameter... parameters) throws HibernateException
    {
        try
        {
            final ManagedQuery managedQuery = new ManagedQuery(query, connection, setFetchSizeEnabled, maxRows, parameters);

            managedQuery.execute();

            return managedQuery;
        } catch (Exception e)
        {
            logger.error("queryFromRdm failed on: {}\ngenerated from: {}", query.getSql(), query.getOriginalHql(), e);
            throw e instanceof HibernateException
                    ? (HibernateException) e
                    : new HibernateException(e);
        }
    }

    /**
     * Scan the parameters for a SQLTransformer, and if found, return the result transformer specified.
     *
     * @param parameters query parameters to scan
     * @return transformer or {@code null}
     */
    private TupleTransformer<?> getResultTransformer(HQLParameter... parameters)
    {
        return Stream.of(parameters)
                .filter(p -> p instanceof SQLTransformer)
                .map(p -> ((SQLTransformer) p).transformer)
                .findFirst().orElse(null);
    }

    /**
     * Reify the values returned by the query.
     *
     * @param resultSet         The result set to process
     * @param resultTransformer Optional result transformer to apply
     * @return List of reified results
     */
    private List<?> reifyValues(ResultSet resultSet, TupleTransformer<?> resultTransformer) throws SQLException
    {
        final List<Object> values = new ArrayList<>();
        final ResultSetMetaData metaData = resultSet.getMetaData();
        final int columnCount = metaData.getColumnCount();
        final boolean singleValue = columnCount == 1;

        while (resultSet.next())
        {
            if (resultTransformer != null)
            {
                values.add(applyResultTransformer(resultSet, resultTransformer));
            } else if (singleValue)
            {
                values.add(getTransformedValue(resultSet, 1));
            } else
            {
                final Object[] rowValues = new Object[columnCount];
                values.add(rowValues);

                for (int index = 0; index < columnCount; index++)
                {
                    rowValues[index] = getTransformedValue(resultSet, index + 1);
                }
            }
        }

        return values;
    }

    /**
     * Apply a result transformer.
     *
     * @param resultSet         Result set to process
     * @param resultTransformer Transformer to apply
     * @return Transformed object
     */
    private Object applyResultTransformer(ResultSet resultSet, TupleTransformer<?> resultTransformer) throws SQLException
    {
        // Create the tuple and alias arrays
        final ResultSetMetaData metaData = resultSet.getMetaData();
        final int columnCount = metaData.getColumnCount();
        final Object[] tuple = new Object[columnCount];
        final String[] aliases = new String[columnCount];

        for (int i = 0; i < columnCount; i++)
        {
            tuple[i] = resultSet.getObject(i + 1);
            aliases[i] = metaData.getColumnLabel(i + 1);
        }

        return resultTransformer.transformTuple(tuple, aliases);
    }

    /**
     * Construct a list of object instances of the given class using the given constructor arguments.
     *
     * @param newClassName Name of class to instantiate
     * @param values       List of Object[] containing the DB values to use arguments to the constructor
     * @param metaData     The meta-data from the result set that produced the "values" data
     * @return List of instantiated objects
     */
    private List<?> constructInstances(String newClassName, List<?> values, ResultSetMetaData metaData) throws SQLException
    {
        final List<Object> objects = new ArrayList<>();
        final Constructor<?> constructor = getConstructor(newClassName, metaData);

        for (Object value : values)
        {
            final Object[] args = (Object[]) value;
            try
            {
                objects.add(constructor.newInstance(args));
            } catch (IllegalArgumentException e)
            {
                // Construct a quality error message since we have failed to match the argument types properly
                final String expected = Stream.of(constructor.getParameterTypes()).map(Class::getSimpleName).collect(Collectors.joining(", "));
                final String actual = Stream.of(args).map(o -> o != null ? o.getClass().getSimpleName() : "null").collect(Collectors.joining(", "));

                final String message = "Failed to instantiate: " + newClassName + "\nexpected arg types: " + expected + "\nActual   arg types: " + actual;
                logger.error(message);
                throw new SQLException(message, e);
            } catch (InstantiationException | IllegalAccessException | InvocationTargetException e)
            {
                final String message = "Failed to construct new " + newClassName;
                logger.error(message);
                throw new SQLException(message, e);
            }
        }

        return objects;
    }

    /**
     * Get the constructor to use to instantiate an object.
     *
     * @param className The name of the class to process
     * @param metaData  Meta-data from the query results (to obtain type information)
     * @return Constructor
     * @throws SQLException if the constructor couldn't be found
     */
    private Constructor<?> getConstructor(String className, ResultSetMetaData metaData) throws SQLException
    {
        // Convert the column types to java types so we can find the constructor
        final int columnCount = metaData.getColumnCount();
        try
        {
            final int[] argSqlTypes = new int[columnCount];
            final Class<?> cls = Class.forName(className);

            for (int i = 1; i <= columnCount; i++)
            {
                argSqlTypes[i - 1] = metaData.getColumnType(i);
            }

            return DatabaseUtils.getConstructorForSqlTypes(cls, argSqlTypes);
        } catch (ClassNotFoundException e)
        {
            final String message = "Can't find class for select: " + className;
            logger.error(message, e);
            throw new SQLException(message, e);
        } catch (NoSuchMethodException e)
        {
            logger.error(e.getMessage());
            throw new SQLException("Can't find constructor for class [" + className + "]", e);
        }
    }

    /**
     * Get and transform an object value from the result set at the given column index.  Convert BigInteger, Date,
     * and Timestamp results into Long values.
     *
     * @param resultSet Result set to access
     * @param index     Index of value to extract from current row in result set
     * @return Object value
     */
    private Object getTransformedValue(ResultSet resultSet, int index) throws SQLException
    {
        Object v = resultSet.getObject(index);

        // Convert BigInteger and Timestamp to Long
        // Use direct equality for speed (no reason to use instanceof)

        final Class<?> cls = v != null ? v.getClass() : null;

        if (cls == BigInteger.class)
        {
            v = ((BigInteger) v).longValue();
        } else if (cls == Timestamp.class)
        {
            v = ((Timestamp) v).getTime();
        } else if (cls == Date.class)
        {
            //noinspection UseOfObsoleteDateTimeApi
            v = ((java.util.Date) v).getTime();
        }
        return v;
    }

    /**
     * Auto-closeable wrapper around an RDMQuery and the PreparedStatement and ResultsSet produced from that query.
     * This ensures that both the prepared statement and the ResultSet are closed at an appropriate time.
     *
     * @since 2.37
     */
    private static final class ManagedQuery implements AutoCloseable
    {
        private static final int FETCH_SIZE = 100; // Hint for the number of rows to retrieve at a time

        private final PreparedStatement statement;
        private ResultSet resultSet;

        /**
         * Construct on the given query and execution parameters.  This immediately creates and prepares
         * the {@code PreparedStatement} from the query, but does not execute it.
         *
         * @param query        Query to process
         * @param connection   DB connection to use
         * @param setFetchSize Pass {@code true} to use {@link PreparedStatement#setFetchSize(int)}
         * @param maxRows      The maximum number of results to return (<= 0 or {@code null} means no limit)
         * @param parameters   The parameters to bind
         * @see #execute()
         */
        ManagedQuery(RDMQuery query, Connection connection, boolean setFetchSize, Integer maxRows, HQLParameter... parameters) throws SQLException
        {
            statement = query.prepareQuery(connection, parameters);

            if (setFetchSize) statement.setFetchSize(FETCH_SIZE); // Make the trip worth while
            if (maxRows != null && maxRows > 0) statement.setMaxRows(maxRows);
        }

        /**
         * Execute the query and obtain the ResultSet.
         */
        void execute() throws SQLException
        {
            resultSet = statement.executeQuery();
        }

        @Override
        public void close() throws SQLException
        {
            if (statement != null) statement.close(); // Also closes produced ResultSet
        }
    }

    /**
     * Iterator to wrap a ResultSet and return reified results on each call to {@link #next()}.
     */
    private static final class ResultSetIterator implements Iterator<IRaptorDataMessage>, AutoCloseable
    {
        private final Connection connection;
        private final ManagedQuery managedQuery;
        private final MessagePersistHelper persistHelper;

        private Boolean autoCommit;
        private boolean beforeFirst = true;

        public ResultSetIterator(Connection connection, ManagedQuery managedQuery, MessagePersistHelper persistHelper)
        {
            this.connection = connection;
            this.managedQuery = managedQuery;
            this.persistHelper = persistHelper;

            try
            {
                // Grab the auto-commit setting on the connection, so we can restore it later
                autoCommit = connection.getAutoCommit();

                // And then turn it off since we don't want the overhead scrolling through RDMs
                if (autoCommit) connection.setAutoCommit(false);
            } catch (SQLException e)
            {
                logger.error("Failed to turn off auto commit.", e);
                autoCommit = null; // unknown, don't try to restore later
            }
        }

        @Override
        public boolean hasNext()
        {
            try
            {
                final ResultSet rs = managedQuery.resultSet;

                // To handle the case of an empty result set, we test isBeforeFirst if this iterator is before first
                return !(beforeFirst && !rs.isBeforeFirst()) && !rs.isLast();
            } catch (SQLException e)
            {
                logger.error("Error: ", e);
            }
            return false;
        }

        @Override
        public IRaptorDataMessage next()
        {
            try
            {
                final ResultSet rs = managedQuery.resultSet;

                if (!rs.next()) throw new NoSuchElementException();
                beforeFirst = false;

                return persistHelper.reifyRDM(rs);
            } catch (SQLException e)
            {
                logger.error("Error: ", e);
            }
            return null;
        }

        @Override
        public void close() throws Exception
        {
            managedQuery.close();

            try
            {
                // Restore the original autoCommit setting on our connection (if we have a known autoCommit value)
                if (autoCommit != null && autoCommit != connection.getAutoCommit())
                {
                    connection.setAutoCommit(autoCommit);
                }
                connection.close();
            } catch (SQLException e)
            {
                logger.error("Failed to set autoCommit = {}", autoCommit, e);
            }
        }
    }
}
